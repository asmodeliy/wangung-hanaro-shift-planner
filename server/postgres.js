import { AsyncLocalStorage } from 'node:async_hooks'
import pg from 'pg'
import { attachDatabasePool } from '@vercel/functions'

const { Pool, types } = pg
types.setTypeParser(20, value => Number(value))

const transactionContext = new AsyncLocalStorage()
const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  max: 5,
  idleTimeoutMillis: 5_000,
  connectionTimeoutMillis: 10_000,
})
attachDatabasePool(pool)

function postgresPlaceholders(sql) {
  // PostgreSQL folds unquoted identifiers to lowercase, while the app's API
  // contract uses camelCase aliases (for example `employeeId`). Preserve them.
  const quotedAliases = sql.replace(/\bAS\s+([a-z][A-Za-z0-9_]*[A-Z][A-Za-z0-9_]*)\b/g, 'AS "$1"')
  let index = 0
  let quoted = false
  let result = ''
  for (let cursor = 0; cursor < quotedAliases.length; cursor++) {
    const character = quotedAliases[cursor]
    if (character === "'" && quotedAliases[cursor - 1] !== '\\') quoted = !quoted
    if (character === '?' && !quoted) result += `$${++index}`
    else result += character
  }
  return result
}

function query(sql, params = []) {
  const client = transactionContext.getStore()
  return (client ?? pool).query(postgresPlaceholders(sql), params)
}

function insertWithId(sql) {
  if (/\bRETURNING\b/i.test(sql)) return sql
  const table = sql.match(/^\s*INSERT\s+INTO\s+([a-z_]+)/i)?.[1]?.toLowerCase()
  return ['employees', 'requests', 'users', 'attendance_reports'].includes(table) ? `${sql} RETURNING id` : sql
}

const database = {
  isPostgres: true,
  prepare(sql) {
    return {
      async get(...params) {
        const result = await query(sql, params)
        return result.rows[0]
      },
      async all(...params) {
        const result = await query(sql, params)
        return result.rows
      },
      async run(...params) {
        const statement = /^\s*INSERT\b/i.test(sql) ? insertWithId(sql) : sql
        const result = await query(statement, params)
        return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id }
      },
    }
  },
  transaction(callback) {
    return async (...args) => {
      const client = await pool.connect()
      try {
        await client.query('BEGIN')
        const result = await transactionContext.run(client, () => callback(...args))
        await client.query('COMMIT')
        return result
      } catch (error) {
        await client.query('ROLLBACK').catch(() => {})
        throw error
      } finally {
        client.release()
      }
    }
  },
  async backup(_label) {
    const tables = ['employees', 'shifts', 'shift_locks', 'locked_months', 'requests', 'app_settings', 'users', 'schedule_history', 'attendance_reports']
    const snapshot = {}
    for (const table of tables) snapshot[table] = (await query(`SELECT * FROM ${table}`)).rows
    const created = await query('INSERT INTO app_backups (snapshot) VALUES ($1::jsonb) RETURNING id, created_at', [JSON.stringify(snapshot)])
    return `Neon 데이터 백업 ${created.rows[0].id} · ${created.rows[0].created_at}`
  },
}

export async function initializePostgres() {
  await query(`CREATE TABLE IF NOT EXISTS employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    employment_type TEXT NOT NULL DEFAULT '정규직',
    duty_type TEXT NOT NULL DEFAULT 'support',
    produce_qualified INTEGER NOT NULL DEFAULT 0,
    produce_backup INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    notes TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    work_rules TEXT NOT NULL DEFAULT '{"allowedShifts":["open","close"],"offRules":[]}'
  )`)
  await query("ALTER TABLE employees ADD COLUMN IF NOT EXISTS duty_type TEXT NOT NULL DEFAULT 'support'")
  await query('ALTER TABLE employees ADD COLUMN IF NOT EXISTS produce_qualified INTEGER NOT NULL DEFAULT 0')
  await query('ALTER TABLE employees ADD COLUMN IF NOT EXISTS produce_backup INTEGER NOT NULL DEFAULT 0')
  await query(`ALTER TABLE employees ADD COLUMN IF NOT EXISTS work_rules TEXT NOT NULL DEFAULT '{"allowedShifts":["open","close"],"offRules":[]}'`)
  await query(`CREATE TABLE IF NOT EXISTS shifts (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    shift_date TEXT NOT NULL,
    code TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(employee_id, shift_date)
  )`)
  await query(`CREATE TABLE IF NOT EXISTS shift_locks (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    shift_date TEXT NOT NULL,
    code TEXT NOT NULL,
    PRIMARY KEY(employee_id, shift_date)
  )`)
  await query(`CREATE TABLE IF NOT EXISTS locked_months (
    month TEXT PRIMARY KEY,
    locked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`)
  await query(`CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    request_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(employee_id, request_date)
  )`)
  await query('CREATE TABLE IF NOT EXISTS app_settings (setting_key TEXT PRIMARY KEY, setting_value TEXT NOT NULL)')
  await query(`CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin', 'employee')),
    employee_id BIGINT UNIQUE REFERENCES employees(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`)
  await query(`CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
  )`)
  await query(`CREATE TABLE IF NOT EXISTS schedule_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month TEXT NOT NULL,
    username TEXT NOT NULL,
    action TEXT NOT NULL,
    snapshot TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`)
  await query(`CREATE TABLE IF NOT EXISTS attendance_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`)
  await query('CREATE INDEX IF NOT EXISTS attendance_reports_created_at_idx ON attendance_reports (created_at DESC, id DESC)')
  await query(`CREATE TABLE IF NOT EXISTS app_backups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`)
  await query('CREATE TABLE IF NOT EXISTS app_meta (meta_key TEXT PRIMARY KEY, meta_value BIGINT NOT NULL)')
  await query("INSERT INTO app_meta (meta_key, meta_value) VALUES ('data_revision', 0) ON CONFLICT(meta_key) DO NOTHING")
}

export default database

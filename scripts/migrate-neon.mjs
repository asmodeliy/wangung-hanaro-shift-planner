import Database from 'better-sqlite3'
import pg from 'pg'
import path from 'node:path'
import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const { Pool } = pg
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = path.resolve(root, process.env.SQLITE_SOURCE ?? 'data/shift-planner.sqlite')
const databaseUrl = process.env.DATABASE_URL_UNPOOLED
const migrationKey = `migration:sqlite:${path.relative(root, sourcePath).replaceAll('\\', '/')}`

if (!databaseUrl) throw new Error('마이그레이션에는 Neon direct 연결용 DATABASE_URL_UNPOOLED 환경변수가 필요합니다.')
if (!existsSync(sourcePath)) throw new Error(`SQLite 원본 파일을 찾을 수 없습니다: ${sourcePath}`)

const source = new Database(sourcePath, { readonly: true, fileMustExist: true })
const pool = new Pool({ connectionString: databaseUrl, max: 1 })
const schema = [
  `CREATE TABLE IF NOT EXISTS employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    employment_type TEXT NOT NULL DEFAULT '정규직',
    duty_type TEXT NOT NULL DEFAULT 'support',
    produce_qualified INTEGER NOT NULL DEFAULT 0,
    produce_backup INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    notes TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    work_rules TEXT NOT NULL DEFAULT '{"allowedShifts":["open","close"],"offRules":[]}'
  )`,
  "ALTER TABLE employees ADD COLUMN IF NOT EXISTS duty_type TEXT NOT NULL DEFAULT 'support'",
  'ALTER TABLE employees ADD COLUMN IF NOT EXISTS produce_qualified INTEGER NOT NULL DEFAULT 0',
  'ALTER TABLE employees ADD COLUMN IF NOT EXISTS produce_backup INTEGER NOT NULL DEFAULT 0',
  `ALTER TABLE employees ADD COLUMN IF NOT EXISTS work_rules TEXT NOT NULL DEFAULT '{"allowedShifts":["open","close"],"offRules":[]}'`,
  `CREATE TABLE IF NOT EXISTS shifts (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    shift_date TEXT NOT NULL,
    code TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(employee_id, shift_date)
  )`,
  `CREATE TABLE IF NOT EXISTS shift_locks (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    shift_date TEXT NOT NULL,
    code TEXT NOT NULL,
    PRIMARY KEY(employee_id, shift_date)
  )`,
  `CREATE TABLE IF NOT EXISTS locked_months (month TEXT PRIMARY KEY, locked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    request_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(employee_id, request_date)
  )`,
  'CREATE TABLE IF NOT EXISTS app_settings (setting_key TEXT PRIMARY KEY, setting_value TEXT NOT NULL)',
  `CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin', 'employee')),
    employee_id BIGINT UNIQUE REFERENCES employees(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS schedule_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month TEXT NOT NULL,
    username TEXT NOT NULL,
    action TEXT NOT NULL,
    snapshot TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS app_backups (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, snapshot JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  'CREATE TABLE IF NOT EXISTS app_meta (meta_key TEXT PRIMARY KEY, meta_value BIGINT NOT NULL)',
  "INSERT INTO app_meta (meta_key, meta_value) VALUES ('data_revision', 0) ON CONFLICT(meta_key) DO NOTHING",
]

function sourceRows(table, columns) {
  return source.prepare(`SELECT ${columns.join(', ')} FROM ${table}`).all()
}

async function insertEmployee(employee, includeId) {
  const columns = ['name', 'employment_type', 'duty_type', 'produce_qualified', 'produce_backup', 'active', 'notes', 'sort_order', 'created_at', 'work_rules']
  const values = columns.map(column => employee[column])
  if (includeId) {
    columns.unshift('id')
    values.unshift(employee.id)
  }
  const placeholders = values.map((_, index) => `$${index + 1}`).join(', ')
  const result = await pool.query(`INSERT INTO employees (${columns.join(', ')}) VALUES (${placeholders}) RETURNING id`, values)
  return Number(result.rows[0].id)
}

try {
  await pool.query('BEGIN')
  for (const statement of schema) await pool.query(statement)

  const alreadyMigrated = await pool.query('SELECT 1 FROM app_settings WHERE setting_key = $1', [migrationKey])
  if (alreadyMigrated.rowCount) throw new Error('이 SQLite 원본은 이미 Neon으로 가져왔습니다. 중복 실행을 막기 위해 중단했습니다.')

  const backup = {}
  for (const table of ['employees', 'shifts', 'shift_locks', 'locked_months', 'requests', 'app_settings', 'users', 'schedule_history']) {
    backup[table] = (await pool.query(`SELECT * FROM ${table}`)).rows
  }
  await pool.query('INSERT INTO app_backups (snapshot) VALUES ($1::jsonb)', [JSON.stringify(backup)])

  const employeeColumns = new Set(source.prepare('PRAGMA table_info(employees)').all().map(column => column.name))
  const employeeProjection = ['id', 'name', 'employment_type', 'duty_type', 'produce_qualified', 'produce_backup', 'active', 'notes', 'sort_order', 'created_at', 'work_rules']
    .map(column => column === 'duty_type' && !employeeColumns.has(column) ? "'support' AS duty_type"
      : column === 'produce_qualified' && !employeeColumns.has(column) ? '0 AS produce_qualified'
        : column === 'produce_backup' && !employeeColumns.has(column) ? '0 AS produce_backup'
          : column === 'work_rules' && !employeeColumns.has(column) ? "'{\"allowedShifts\":[\"open\",\"close\"],\"offRules\":[]}' AS work_rules"
            : column)
  const sourceEmployees = sourceRows('employees', employeeProjection)
  const targetEmployees = (await pool.query('SELECT id, name FROM employees')).rows
  const employeeMap = new Map()
  const claimedTargetIds = new Set()

  for (const employee of sourceEmployees) {
    const namedMatches = targetEmployees.filter(target => target.name === employee.name)
    if (namedMatches.length > 1) throw new Error(`Neon에 같은 이름의 직원이 여러 명 있어 안전하게 연결할 수 없습니다 (직원 ID ${employee.id}).`)
    let target = namedMatches[0]
    if (!target) {
      const idCollision = targetEmployees.some(row => Number(row.id) === Number(employee.id))
      const id = await insertEmployee(employee, !idCollision)
      target = { id, name: employee.name }
      targetEmployees.push(target)
    }
    if (claimedTargetIds.has(Number(target.id))) throw new Error(`여러 SQLite 직원을 같은 Neon 직원에게 연결할 수 없습니다 (직원 ID ${employee.id}).`)
    claimedTargetIds.add(Number(target.id))
    employeeMap.set(Number(employee.id), Number(target.id))
    await pool.query(`UPDATE employees SET name=$1, employment_type=$2, duty_type=$3, produce_qualified=$4, produce_backup=$5,
      active=$6, notes=$7, sort_order=$8, created_at=$9, work_rules=$10 WHERE id=$11`, [
      employee.name, employee.employment_type, employee.duty_type ?? 'support', employee.produce_qualified ?? 0,
      employee.produce_backup ?? 0, employee.active, employee.notes, employee.sort_order, employee.created_at,
      employee.work_rules ?? '{"allowedShifts":["open","close"],"offRules":[]}', target.id,
    ])
  }

  for (const row of sourceRows('shifts', ['employee_id', 'shift_date', 'code', 'updated_at'])) {
    const employeeId = employeeMap.get(Number(row.employee_id))
    if (!employeeId) throw new Error(`근무 직원 연결을 찾을 수 없습니다 (직원 ID ${row.employee_id}).`)
    await pool.query(`INSERT INTO shifts (employee_id, shift_date, code, updated_at) VALUES ($1,$2,$3,$4)
      ON CONFLICT(employee_id, shift_date) DO UPDATE SET code=EXCLUDED.code, updated_at=EXCLUDED.updated_at`, [employeeId, row.shift_date, row.code, row.updated_at])
  }
  for (const row of sourceRows('shift_locks', ['employee_id', 'shift_date', 'code'])) {
    const employeeId = employeeMap.get(Number(row.employee_id))
    if (!employeeId) throw new Error(`고정 직원 연결을 찾을 수 없습니다 (직원 ID ${row.employee_id}).`)
    await pool.query(`INSERT INTO shift_locks (employee_id, shift_date, code) VALUES ($1,$2,$3)
      ON CONFLICT(employee_id, shift_date) DO UPDATE SET code=EXCLUDED.code`, [employeeId, row.shift_date, row.code])
  }
  for (const row of sourceRows('locked_months', ['month', 'locked_at'])) {
    await pool.query(`INSERT INTO locked_months (month, locked_at) VALUES ($1,$2)
      ON CONFLICT(month) DO UPDATE SET locked_at=EXCLUDED.locked_at`, [row.month, row.locked_at])
  }
  for (const row of sourceRows('requests', ['employee_id', 'request_date', 'status', 'created_at'])) {
    const employeeId = employeeMap.get(Number(row.employee_id))
    if (!employeeId) throw new Error(`희망휴무 직원 연결을 찾을 수 없습니다 (직원 ID ${row.employee_id}).`)
    await pool.query(`INSERT INTO requests (employee_id, request_date, status, created_at) VALUES ($1,$2,$3,$4)
      ON CONFLICT(employee_id, request_date) DO UPDATE SET status=EXCLUDED.status, created_at=EXCLUDED.created_at`, [employeeId, row.request_date, row.status, row.created_at])
  }
  for (const row of sourceRows('app_settings', ['setting_key', 'setting_value'])) {
    await pool.query(`INSERT INTO app_settings (setting_key, setting_value) VALUES ($1,$2)
      ON CONFLICT(setting_key) DO UPDATE SET setting_value=EXCLUDED.setting_value`, [row.setting_key, row.setting_value])
  }

  const targetUsers = new Map((await pool.query('SELECT id, username, role, employee_id FROM users')).rows.map(user => [user.username, user]))
  const sourceUsers = sourceRows('users', ['id', 'username', 'password_hash', 'role', 'employee_id', 'created_at'])
  for (const user of sourceUsers) {
    const employeeId = user.employee_id == null ? null : employeeMap.get(Number(user.employee_id))
    if (user.employee_id != null && !employeeId) throw new Error(`계정 직원 연결을 찾을 수 없습니다 (계정 ID ${user.id}).`)
    const existing = targetUsers.get(user.username)
    if (existing) {
      if (existing.role !== user.role || Number(existing.employee_id ?? 0) !== Number(employeeId ?? 0)) {
        throw new Error('같은 로그인 아이디가 다른 계정에 연결되어 있어 자동 병합을 중단했습니다.')
      }
      continue
    }
    const result = await pool.query(`INSERT INTO users (username, password_hash, role, employee_id, created_at)
      VALUES ($1,$2,$3,$4,$5) RETURNING id`, [user.username, user.password_hash, user.role, employeeId, user.created_at])
    targetUsers.set(user.username, { id: result.rows[0].id, username: user.username, role: user.role, employee_id: employeeId })
  }

  for (const row of sourceRows('schedule_history', ['month', 'username', 'action', 'snapshot', 'created_at'])) {
    const snapshot = JSON.parse(row.snapshot)
    for (const collection of ['shifts', 'locks']) {
      for (const item of snapshot[collection] ?? []) {
        const targetId = employeeMap.get(Number(item.employeeId))
        if (!targetId) throw new Error(`변경 이력 직원 연결을 찾을 수 없습니다 (직원 ID ${item.employeeId}).`)
        item.employeeId = targetId
      }
    }
    await pool.query('INSERT INTO schedule_history (month, username, action, snapshot, created_at) VALUES ($1,$2,$3,$4,$5)', [row.month, row.username, row.action, JSON.stringify(snapshot), row.created_at])
  }

  for (const name of ['reference-import.json', 'reference-import-history.json']) {
    const file = path.join(path.dirname(sourcePath), name)
    if (existsSync(file)) await pool.query('INSERT INTO app_settings (setting_key, setting_value) VALUES ($1,$2) ON CONFLICT(setting_key) DO UPDATE SET setting_value=EXCLUDED.setting_value', [`file:${name}`, readFileSync(file, 'utf8').replace(/^\uFEFF/, '')])
  }
  const referenceImage = path.join(path.dirname(sourcePath), 'reference-schedule.png')
  if (existsSync(referenceImage)) await pool.query('INSERT INTO app_settings (setting_key, setting_value) VALUES ($1,$2) ON CONFLICT(setting_key) DO UPDATE SET setting_value=EXCLUDED.setting_value', ['file:reference-schedule.png', readFileSync(referenceImage).toString('base64')])

  for (const table of ['employees', 'requests', 'users', 'schedule_history']) {
    await pool.query(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1), EXISTS (SELECT 1 FROM ${table}))`)
  }
  await pool.query('UPDATE app_meta SET meta_value=meta_value+1 WHERE meta_key=\'data_revision\'')
  await pool.query('INSERT INTO app_settings (setting_key, setting_value) VALUES ($1,$2)', [migrationKey, new Date().toISOString()])

  const summary = await pool.query(`SELECT
    (SELECT count(*)::int FROM employees) AS employees,
    (SELECT count(*)::int FROM shifts) AS shifts,
    (SELECT count(*)::int FROM shift_locks) AS shift_locks,
    (SELECT count(*)::int FROM locked_months) AS locked_months,
    (SELECT count(*)::int FROM requests) AS requests,
    (SELECT count(*)::int FROM users) AS users,
    (SELECT count(*)::int FROM schedule_history) AS history`)
  await pool.query('COMMIT')
  console.log(JSON.stringify({ importedEmployees: sourceEmployees.length, importedShifts: source.prepare('SELECT COUNT(*) n FROM shifts').get().n, importedLocks: source.prepare('SELECT COUNT(*) n FROM shift_locks').get().n, importedRequests: source.prepare('SELECT COUNT(*) n FROM requests').get().n, importedHistory: source.prepare('SELECT COUNT(*) n FROM schedule_history').get().n, neon: summary.rows[0], remoteBackupCreated: true }))
} catch (error) {
  await pool.query('ROLLBACK').catch(() => {})
  throw error
} finally {
  source.close()
  await pool.end()
}
